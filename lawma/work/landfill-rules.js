/* MOD-04 proposed landfill rules. Sample thresholds only; LAWMA landfill engineering and LASEPA approval is required. */
const SURVEY_RMSE_LIMIT_CM=5;
const CAPPING_TRIGGER=0.1;
const WASTE_DENSITY_T_M3=0.9;
const VOLUME_VARIANCE_LIMIT=0.15;
const PLANT_MIN_LOAD=25;
const INVOICE_TOLERANCE=0.05;
const METHANE_WARN=1;
const METHANE_STOP=2.5;
const FIRE_WARN_C=60;
const FIRE_STOP_C=80;
const SLOPE_WARN_MM=10;
const SLOPE_STOP_MM=25;
const PICKER_MIN_AGE=18;
const PICKER_HOURS=[7,18];
const PICKER_PASS_DAYS=90;
const LANDFILL_ROLES=['management','operations','auditor','admin'];
const surveyAccepted=s=>!!s&&s.rmseCm<=SURVEY_RMSE_LIMIT_CM;
const airspaceLeft=(permitted,used)=>Math.max(0,permitted-used);
const fillRate=(a,b)=>{const d=(new Date(b.date)-new Date(a.date))/86400000;return d>0?Math.max(0,(b.usedM3-a.usedM3)/d):0};
const daysLeft=(left,rate)=>rate>0?Math.floor(left/rate):Infinity;
const cappingDue=(permitted,used)=>airspaceLeft(permitted,used)/permitted<=CAPPING_TRIGGER;
const volumeVariance=(m3,tonnes)=>{const exp=tonnes/WASTE_DENSITY_T_M3;return exp?Math.abs(m3-exp)/exp:0};
const billableHours=logs=>Math.round(logs.filter(l=>l.load>=PLANT_MIN_LOAD&&l.inFence).reduce((n,l)=>n+l.hours,0)*10)/10;
const invoiceHeld=(invoiced,billable)=>invoiced>billable*(1+INVOICE_TOLERANCE);
const methaneLevel=v=>v>=METHANE_STOP?'Stop':v>=METHANE_WARN?'Warning':'Normal';
const fireLevel=c=>c>=FIRE_STOP_C?'Stop':c>=FIRE_WARN_C?'Warning':'Normal';
const slopeLevel=mm=>mm>=SLOPE_STOP_MM?'Stop':mm>=SLOPE_WARN_MM?'Warning':'Normal';
const sensorLevel=s=>s.kind==='Methane'?methaneLevel(s.value):s.kind==='Subsurface temperature'?fireLevel(s.value):slopeLevel(s.value);
const worstLevel=levels=>levels.includes('Stop')?'Stop':levels.includes('Warning')?'Warning':'Normal';
const pickerAge=(dob,now)=>{const d=new Date(dob),n=new Date(now);let a=n.getFullYear()-d.getFullYear();if(n.getMonth()<d.getMonth()||(n.getMonth()===d.getMonth()&&n.getDate()<d.getDate()))a--;return a};
const passValid=(p,now)=>!!p.expires&&new Date(p.expires)>=new Date(now)&&!p.suspended;
const gateRefusals=(p,c)=>[!c.biometric&&'Fingerprint does not match the pass',!passValid(p,c.now)&&'Pass expired or suspended',pickerAge(p.dob,c.now)<PICKER_MIN_AGE&&'Under 18: entry prohibited',!c.ppe&&'No boots, gloves and reflective vest',(c.hour<PICKER_HOURS[0]||c.hour>=PICKER_HOURS[1])&&'Outside picking hours (07:00–18:00)',c.faceStatus==='Stop'&&p.zone==='Active face'&&'Active face closed for safety'].filter(Boolean);
